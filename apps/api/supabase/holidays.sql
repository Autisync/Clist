-- fn_is_working_day: byte-faithful port of packages/core/src/deadlines.ts's
-- isWorkingDay() — not a Saturday/Sunday, and no `public`-kind holiday on
-- this date (national, or matching p_municipality when given). extract(dow
-- from date) returns 0=Sunday..6=Saturday for a `date` value, same numbering
-- JS's Date.getUTCDay() uses, so the weekend check is the same comparison,
-- not just the same intent.
create or replace function fn_is_working_day(p_date date, p_municipality text default null)
returns boolean
language sql
stable
as $$
  select extract(dow from p_date) not in (0, 6)
    and not exists (
      select 1 from pt_holiday
      where holiday_date = p_date
        and kind = 'public'
        and (municipality is null or municipality = p_municipality)
    );
$$;

-- fn_add_working_days: byte-faithful port of addWorkingDays() — same
-- "day the fromDate itself falls on is never counted" semantics (the loop
-- always advances the cursor before checking), same "count only forward"
-- direction (p_days is assumed positive, same as the ported function never
-- handled negative/zero specially either).
create or replace function fn_add_working_days(p_from_date date, p_days int, p_municipality text default null)
returns date
language plpgsql
stable
as $$
declare
  v_cursor date := p_from_date;
  v_remaining int := p_days;
begin
  while v_remaining > 0 loop
    v_cursor := v_cursor + 1;
    if fn_is_working_day(v_cursor, p_municipality) then
      v_remaining := v_remaining - 1;
    end if;
  end loop;
  return v_cursor;
end;
$$;

