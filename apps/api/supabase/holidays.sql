-- Postgres UNIQUE constraints treat every NULL as distinct, so a plain
-- unique(holiday_date, municipality) would not actually stop a duplicate
-- national row (municipality IS NULL) from being inserted twice — an
-- expression index normalizing null to '' is what actually enforces it.
create unique index idx_pt_holiday_date_municipality on pt_holiday (holiday_date, coalesce(municipality, ''));

