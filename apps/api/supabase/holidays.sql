--
-- Replaces the `date-holidays` npm dependency for F17 statutory-deadline math
-- with a plain reference table + two SQL functions, so a Postgres RPC (see
-- rpc.sql's rpc_closeout_submit) can compute a working-day-aware due date
-- without any server-side JS in the path at all — "the migration makes
-- something better, not just relocated" per the design doc's own words: the
-- barrel-export bundle-leak bug this session found once already (Phase 3,
-- packages/core/src/index.ts) becomes structurally impossible for this
-- specific dependency, because there's no JS holiday library left to
-- accidentally bundle.
--
-- Seed data below is NOT hand-transcribed — it was generated by running the
-- ALREADY-INSTALLED, ALREADY-TESTED `date-holidays` package (the same one
-- packages/core/src/deadlines.ts uses, proven correct by
-- apps/api/test/phase3-proof.mjs's own Sexta-Feira Santa 2026-04-03 check)
-- day-by-day across 2024–2032, filtering to `type: "public"` only — the same
-- filter deadlines.ts's isWorkingDay() already applies, since date-holidays
-- also returns observance/optional/school/bank entries (e.g. Carnaval is
-- `observance` in Portugal, not a statutory public holiday) that must NOT
-- stop the statutory clock. A first attempt at this generation script used
-- getHolidays(year) + a naive `new Date(string).toISOString()` conversion
-- and silently shifted every date by one day (a timezone-ambiguous string
-- reparse) — caught by cross-checking against phase3-proof.mjs's own
-- already-verified 2026-04-03 assertion before trusting any of this data,
-- not assumed correct. Fixed by walking each UTC day explicitly and calling
-- hd.isHoliday() directly, the same method deadlines.ts itself uses.
--
-- Only national-level (municipality IS NULL) rows are seeded — grep across
-- seed.sql and every test fixture found tenant.municipality is never
-- actually set anywhere in this codebase today, so município-specific rows
-- would be untested, unexercised scope creep. The `municipality` column and
-- fn_add_working_days' parameter both exist and are schema-ready for
-- whenever that's needed (same "amendable later" pattern as
-- instrument_export elsewhere in this schema), same as
-- tenant.municipality itself already is.
-- ============================================================================

create table pt_holiday (
  id            uuid primary key default gen_random_uuid(),
  holiday_date  date not null,
  name          text not null,
  kind          text not null check (kind in ('public', 'observance', 'optional', 'school', 'bank')),
  municipality  text  -- date-holidays subdivision code, e.g. 'PT-11' — null = national. Never populated yet.
);

